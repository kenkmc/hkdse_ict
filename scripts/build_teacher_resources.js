// Generated deployment artifact; course_data.js remains the only course catalogue.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'course_data.js'), 'utf8') + '\nthis.catalogue = courseData;', context);
vm.runInNewContext(fs.readFileSync(path.join(root, 'learning_data.js'), 'utf8'), context);
const resources = context.catalogue.flatMap(section => section.items.map(item => ({ id: item.id, title: item.title, file: item.file, type: item.type,
  layers: context.window.HKDSE_ICT_LEARNING.pages[item.id]?.layeredLearning?.levels?.length || 0,
  game: Boolean(context.window.HKDSE_ICT_LEARNING.pages[item.id]?.game) })));
const output = '// Generated by scripts/build_teacher_resources.js from course_data.js. Do not edit manually.\nconst TEACHER_ADMIN_RESOURCES = Object.freeze(' + JSON.stringify(resources, null, 2) + ');\n';
const destination = path.join(root, 'google-apps-script', 'TeacherResources.gs');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('TeacherResources.gs is stale. Run node scripts/build_teacher_resources.js');
} else fs.writeFileSync(destination, output);
console.log(`Teacher resource catalogue: ${resources.length} entries${process.argv.includes('--check') ? ' verified' : ' built'}.`);
